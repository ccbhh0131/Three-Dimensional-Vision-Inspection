void MeshLoaderTest::invalidMagic()
{
    const QByteArray properties =
        "property float x\n"
        "property float y\n"
        "property float z\n";
    QByteArray header = makeHeader(3, properties);
    header.replace(0, 3, "nope");

    const QString path = writeFixture(QStringLiteral("invalid_magic"), header, {});
    QVERIFY(!path.isEmpty());

    const MeshLoadResult result = PlyMeshLoader::load(path);
    QVERIFY(!result.success);
    QCOMPARE(result.errorCode, MeshLoadError::InvalidHeader);
}

