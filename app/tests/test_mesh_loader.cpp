void MeshLoaderTest::boundingBox()
{
    BoundingBox box;
    QVERIFY(box.isEmpty());
    QCOMPARE(box.center(), QVector3D(0.0f, 0.0f, 0.0f));
    QCOMPARE(box.extent(), QVector3D(0.0f, 0.0f, 0.0f));

    box.expand(QVector3D(5.0f, -2.0f, 10.0f));
    box.expand(QVector3D(-1.0f, 4.0f, 3.0f));
    QVERIFY(!box.isEmpty());
    QCOMPARE(box.minimum(), QVector3D(-1.0f, -2.0f, 3.0f));
    QCOMPARE(box.maximum(), QVector3D(5.0f, 4.0f, 10.0f));
    QCOMPARE(box.center(), QVector3D(2.0f, 1.0f, 6.5f));
    QCOMPARE(box.extent(), QVector3D(6.0f, 6.0f, 7.0f));

    box.reset();
    QVERIFY(box.isEmpty());
}

void MeshLoaderTest::sourceCoordinatePreservation()
{
    const QByteArray properties =
        "property float x\n"
        "property float y\n"
        "property float z\n";
    const QVector<QVector3D> sourcePositions = {
        QVector3D(123.5f, -456.25f, 0.125f),
        QVector3D(124.5f, -456.25f, 0.125f),
        QVector3D(123.5f, -455.25f, 0.125f)
    };
    QByteArray payload;
    for (const QVector3D& position : sourcePositions) {
        appendFloatLE(payload, position.x());
        appendFloatLE(payload, position.y());
        appendFloatLE(payload, position.z());
    }
    appendUChar(payload, 3);
    appendInt32LE(payload, 0);
    appendInt32LE(payload, 1);
    appendInt32LE(payload, 2);

    const QString path = writeFixture(
        QStringLiteral("source_coordinates"),
        makeHeader(3, properties),
        payload);
    QVERIFY(!path.isEmpty());

    const MeshLoadResult result = PlyMeshLoader::load(path);
    QVERIFY2(result.success, qPrintable(result.message));
    QCOMPARE(result.mesh.vertices.size(), qsizetype(3));
    for (int index = 0; index < sourcePositions.size(); ++index) {
        const QVector3D actual = result.mesh.vertices.at(index).position;
        const QVector3D expected = sourcePositions.at(index);
        QVERIFY(qAbs(actual.x() - expected.x()) < 1.0e-6f);
        QVERIFY(qAbs(actual.y() - expected.y()) < 1.0e-6f);
        QVERIFY(qAbs(actual.z() - expected.z()) < 1.0e-6f);
    }
    QCOMPARE(result.mesh.boundingBox.minimum(), QVector3D(123.5f, -456.25f, 0.125f));
    QCOMPARE(result.mesh.boundingBox.maximum(), QVector3D(124.5f, -455.25f, 0.125f));
}

void MeshLoaderTest::realPoissonSmoke()
{
    const QString path = qEnvironmentVariable("STAGE4B1_REAL_PLY");
    if (path.isEmpty()) {
        QSKIP("STAGE4B1_REAL_PLY is not set; real Poisson smoke is opt-in");
    }
    if (!QFileInfo::exists(path)) {
        QSKIP(qPrintable(QStringLiteral("real Poisson file does not exist: %1").arg(path)));
    }

    const MeshLoadResult result = PlyMeshLoader::load(path);
    QVERIFY2(result.success, qPrintable(result.message));
    QCOMPARE(result.mesh.vertices.size(), qsizetype(329862));
    QCOMPARE(result.mesh.triangleCount(), qsizetype(635990));
    QVERIFY(result.mesh.hasColors);
    QVERIFY(result.mesh.hasNormals);
    QVERIFY(result.mesh.normalsDerived);
    QVERIFY(!result.mesh.boundingBox.isEmpty());

    qInfo().noquote()
        << QStringLiteral(
               "REAL_POISSON vertices=%1 triangles=%2 load_ms=%3 normal_ms=%4 total_ms=%5 approx_cpu_bytes=%6")
               .arg(result.mesh.vertices.size())
               .arg(result.mesh.triangleCount())
               .arg(result.metrics.loadMilliseconds, 0, 'f', 3)
               .arg(result.metrics.normalGenerationMilliseconds, 0, 'f', 3)
               .arg(result.metrics.totalMilliseconds, 0, 'f', 3)
               .arg(result.metrics.approximateCpuBytes);
}

