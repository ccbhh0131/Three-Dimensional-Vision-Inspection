void MeshLoaderTest::initTestCase()
{
    const QString configuredRoot = qEnvironmentVariable("STAGE4B1_TEST_ROOT");
    const QString baseRoot = configuredRoot.isEmpty()
        ? QDir(QCoreApplication::applicationDirPath()).filePath(QStringLiteral("stage4b1_fixtures"))
        : configuredRoot;
    m_root = QDir(baseRoot).filePath(
        QStringLiteral("run_%1").arg(QUuid::createUuid().toString(QUuid::WithoutBraces)));
    QVERIFY2(QDir().mkpath(m_root), qPrintable(m_root));
}

void MeshLoaderTest::cleanupTestCase()
{
    if (!m_root.isEmpty()) {
        QVERIFY2(QDir(m_root).removeRecursively(), qPrintable(m_root));
    }
}

QString MeshLoaderTest::writeFixture(
    const QString& name,
    const QByteArray& header,
    const QByteArray& payload)
{
    const QString path = QDir(m_root).filePath(name + QStringLiteral(".ply"));
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly)) {
        return {};
    }
    if (file.write(header) != header.size() || file.write(payload) != payload.size()) {
        return {};
    }
    file.close();
    return path;
}

void MeshLoaderTest::validTriangleMesh()
{
    const QByteArray properties =
        "property float x\n"
        "property float y\n"
        "property float z\n"
        "property uchar red\n"
        "property uchar green\n"
        "property uchar blue\n";
    QByteArray payload;
    appendFloatLE(payload, 10.0f);
    appendFloatLE(payload, -20.0f);
    appendFloatLE(payload, 30.0f);
    appendUChar(payload, 255);
    appendUChar(payload, 0);
    appendUChar(payload, 0);
    appendFloatLE(payload, 12.0f);
    appendFloatLE(payload, -20.0f);
    appendFloatLE(payload, 30.0f);
    appendUChar(payload, 0);
    appendUChar(payload, 255);
    appendUChar(payload, 0);
    appendFloatLE(payload, 10.0f);
    appendFloatLE(payload, -18.0f);
    appendFloatLE(payload, 30.0f);
    appendUChar(payload, 0);
    appendUChar(payload, 0);
    appendUChar(payload, 255);
    appendUChar(payload, 3);
    appendInt32LE(payload, 0);
    appendInt32LE(payload, 1);
    appendInt32LE(payload, 2);

    const QString path = writeFixture(QStringLiteral("valid_triangle"), makeHeader(3, properties), payload);
    QVERIFY(!path.isEmpty());

    const MeshLoadResult result = PlyMeshLoader::load(path);
    QVERIFY2(result.success, qPrintable(result.message));
    QCOMPARE(result.mesh.vertices.size(), qsizetype(3));
    QCOMPARE(result.mesh.triangleCount(), qsizetype(1));
    QCOMPARE(result.mesh.indices, QVector<quint32>({0, 1, 2}));
    QVERIFY(result.mesh.hasColors);
    QVERIFY(result.mesh.hasNormals);
    QVERIFY(result.mesh.normalsDerived);
    QCOMPARE(result.mesh.vertices.at(0).color.red, quint8(255));
    QCOMPARE(result.mesh.vertices.at(1).color.green, quint8(255));
    QCOMPARE(result.mesh.vertices.at(2).color.blue, quint8(255));
    QCOMPARE(result.mesh.boundingBox.minimum(), QVector3D(10.0f, -20.0f, 30.0f));
    QCOMPARE(result.mesh.boundingBox.maximum(), QVector3D(12.0f, -18.0f, 30.0f));
    QCOMPARE(result.mesh.boundingBox.center(), QVector3D(11.0f, -19.0f, 30.0f));
    QCOMPARE(result.mesh.boundingBox.extent(), QVector3D(2.0f, 2.0f, 0.0f));
    QVERIFY(qAbs(result.mesh.vertices.at(0).normal.z() - 1.0f) < 1.0e-5f);
}

void MeshLoaderTest::multipleTriangles()
{
    const QByteArray properties =
        "property float x\n"
        "property float y\n"
        "property float z\n";
    QByteArray payload;
    const QVector<QVector3D> positions = {
        QVector3D(0.0f, 0.0f, 0.0f),
        QVector3D(1.0f, 0.0f, 0.0f),
        QVector3D(1.0f, 1.0f, 0.0f),
        QVector3D(0.0f, 1.0f, 0.0f)
    };
    for (const QVector3D& position : positions) {
        appendFloatLE(payload, position.x());
        appendFloatLE(payload, position.y());
        appendFloatLE(payload, position.z());
    }
    appendUChar(payload, 3);
    appendInt32LE(payload, 0);
    appendInt32LE(payload, 1);
    appendInt32LE(payload, 2);
    appendUChar(payload, 3);
    appendInt32LE(payload, 0);
    appendInt32LE(payload, 2);
    appendInt32LE(payload, 3);

    const QString path = writeFixture(
        QStringLiteral("multiple_triangles"),
        makeHeader(4, properties, true, 2),
        payload);
    QVERIFY(!path.isEmpty());

    const MeshLoadResult result = PlyMeshLoader::load(path);
    QVERIFY2(result.success, qPrintable(result.message));
    QCOMPARE(result.mesh.triangleCount(), qsizetype(2));
    QCOMPARE(result.mesh.indices, QVector<quint32>({0, 1, 2, 0, 2, 3}));
    QVERIFY(result.mesh.hasNormals);
    for (const MeshVertex& vertex : result.mesh.vertices) {
        QVERIFY(vertex.normal.z() > 0.99f);
        QVERIFY(std::isfinite(vertex.normal.x()));
        QVERIFY(std::isfinite(vertex.normal.y()));
        QVERIFY(std::isfinite(vertex.normal.z()));
    }
}

