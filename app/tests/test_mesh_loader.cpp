void appendUChar(QByteArray& bytes, quint8 value)
{
    bytes.append(static_cast<char>(value));
}

void appendFloatLE(QByteArray& bytes, float value)
{
    quint32 bits = 0;
    std::memcpy(&bits, &value, sizeof(value));
    bytes.append(static_cast<char>(bits & 0xffu));
    bytes.append(static_cast<char>((bits >> 8) & 0xffu));
    bytes.append(static_cast<char>((bits >> 16) & 0xffu));
    bytes.append(static_cast<char>((bits >> 24) & 0xffu));
}

void appendInt32LE(QByteArray& bytes, qint32 value)
{
    quint32 bits = 0;
    std::memcpy(&bits, &value, sizeof(value));
    bytes.append(static_cast<char>(bits & 0xffu));
    bytes.append(static_cast<char>((bits >> 8) & 0xffu));
    bytes.append(static_cast<char>((bits >> 16) & 0xffu));
    bytes.append(static_cast<char>((bits >> 24) & 0xffu));
}

QByteArray makeHeader(
    quint32 vertexCount,
    const QByteArray& vertexProperties,
    bool includeFace = true,
    quint32 faceCount = 1,
    const QByteArray& faceProperties = "property list uchar int vertex_indices\n",
    const QByteArray& format = "binary_little_endian")
{
    QByteArray header;
    header += "ply\n";
    header += "format ";
    header += format;
    header += " 1.0\n";
    header += "comment generated by Stage 4B-1 tests\n";
    header += "element vertex ";
    header += QByteArray::number(vertexCount);
    header += "\n";
    header += vertexProperties;
    if (includeFace) {
        header += "element face ";
        header += QByteArray::number(faceCount);
        header += "\n";
        header += faceProperties;
    }
    header += "end_header\n";
    return header;
}

